// Builds src/web/js/i18n/*.js from i18n/strings-*.txt.
// Each entry there is five lines: Portuguese (Brazil) = the text used in the code, then
// English, Spanish, Italian and German; entries are separated by a blank line.
// European Portuguese is derived from the Brazilian text by the word rules below, plus
// the hand-written entries of i18n/pt-PT.txt (two lines each: Brazil, Portugal).
//   node scripts/build-i18n.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const blocks = (file) =>
  readFileSync(join(root, 'i18n', file), 'utf8')
    .split(/\r?\n\s*\r?\n/)
    .map((b) => b.split(/\r?\n/).filter((l) => l.trim()))
    .filter((b) => b.length);

const LANGS = ['en', 'es', 'it', 'de'];
const dict = Object.fromEntries(LANGS.map((l) => [l, {}]));
const keys = [];
for (const file of readdirSync(join(root, 'i18n'))
  .filter((f) => /^strings-.*\.txt$/.test(f))
  .sort())
  for (const b of blocks(file)) {
    if (b.length !== 5)
      throw new Error(`${file}: entry "${b[0]}" has ${b.length} lines, expected 5`);
    if (keys.includes(b[0])) throw new Error(`${file}: "${b[0]}" appears twice`);
    keys.push(b[0]);
    const marks = (s) => (s.match(/\{\w+\}/g) || []).sort().join();
    LANGS.forEach((l, i) => {
      if (marks(b[i + 1]) !== marks(b[0]))
        throw new Error(`${file}: {placeholders} differ in "${b[0]}" (${l})`);
      dict[l][b[0]] = b[i + 1];
    });
  }

// Brazil → Portugal, whole words, longest rules first.
const RULES = [
  [/\bna tela\b/g, 'no ecrã'],
  [/\bNa tela\b/g, 'No ecrã'],
  [/\bda tela\b/g, 'do ecrã'],
  [/\bà tela\b/g, 'ao ecrã'],
  [/\ba tela\b/g, 'o ecrã'],
  [/\btela\b/g, 'ecrã'],
  [/\bTela\b/g, 'Ecrã'],
  [/\bnum arquivo\b/g, 'num ficheiro'],
  [/\barquivos\b/g, 'ficheiros'],
  [/\bArquivos\b/g, 'Ficheiros'],
  [/\barquivo\b/g, 'ficheiro'],
  [/\bArquivo\b/g, 'Ficheiro'],
  [/\bSalvando\b/g, 'A guardar'],
  [/\bSalvar\b/g, 'Guardar'],
  [/\bsalvar\b/g, 'guardar'],
  [/\bSalve\b/g, 'Guarde'],
  [/\bSalvo\b/g, 'Guardado'],
  [/\bsalvos\b/g, 'guardados'],
  [/\bsalvo\b/g, 'guardado'],
  [/\bcâmeras\b/g, 'câmaras'],
  [/\bcâmera\b/g, 'câmara'],
  [/\bConfigurações\b/g, 'Definições'],
  [/\bconfigurações\b/g, 'definições'],
  [/\bna aba\b/g, 'no separador'],
  [/\baba\b/g, 'separador'],
  [/\bAba\b/g, 'Separador'],
  [/\bCadastre\b/g, 'Registe'],
  [/\bdegradê\b/g, 'gradiente'],
  [/\bDegradê\b/g, 'Gradiente'],
  [/\bAO VIVO\b/g, 'EM DIRETO'],
  [/\bAo vivo\b/g, 'Em direto'],
  [/\bEsmaecer\b/g, 'Desvanecer'],
  [/\bQuicar\b/g, 'Saltar'],
  [/\bGirar\b/g, 'Rodar'],
  [/\bIngresso\b/g, 'Bilhete'],
  [/\bDá para\b/g, 'É possível'],
  [/\bo aplicativo\b/g, 'a aplicação'],
  [/\bdo aplicativo\b/g, 'da aplicação'],
  [/\baplicativo\b/g, 'aplicação'],
  [/\bDigite\b/g, 'Escreva'],
  [/\bestá respondendo\b/g, 'está a responder'],
  [/\brolando\b/g, 'a passar'],
  [/\bseu OBS\b/g, 'seu OBS'],
];
const pt = {};
for (const key of [...keys]) {
  let out = key;
  for (const [from, to] of RULES) out = out.replace(from, to);
  if (out !== key) pt[key] = out;
}
for (const b of blocks('pt-PT.txt')) {
  if (b.length !== 2) throw new Error(`pt-PT.txt: entry "${b[0]}" needs 2 lines`);
  if (!keys.includes(b[0])) throw new Error(`pt-PT.txt: "${b[0]}" is not a known text`);
  pt[b[0]] = b[1];
}

const write = (name, table) =>
  writeFileSync(
    join(root, 'src/web/js/i18n', `${name}.js`),
    `// Generated by scripts/build-i18n.mjs from i18n/*.txt. Do not edit by hand.\nexport default ${JSON.stringify(table, null, 2)};\n`,
  );
for (const l of LANGS) write(l, dict[l]);
write('pt-PT', pt);
writeFileSync(join(root, 'i18n', 'keys.json'), JSON.stringify(keys, null, 2) + '\n');
console.log(`${keys.length} texts; pt-PT differs in ${Object.keys(pt).length}`);
